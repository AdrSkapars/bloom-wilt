#!/usr/bin/env python3
"""Headline comparison of the paired top-5 lists collected by collect_top5.py.

Run per direction; the two contexts are always target vs elicited, what changes is whose
tokens they are forced along:

  python -X utf8 experiments/postpaper/api_tilt/top5_overlap.py --arm vanilla_15s
  python -X utf8 experiments/postpaper/api_tilt/top5_overlap.py --arm api_elicited_15s

Alternatives come back as token STRINGS (the provider returns no ids for them), so set
overlap is computed on strings.
"""
import argparse
import json
import math
import statistics as st
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
ARM_ROOT = REPO / "experiments/postpaper/runs_dsv4/self_harm/deepseek_v4_flash"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--arm", default="vanilla_15s")
    ap.add_argument("--round", type=int, default=1)
    args = ap.parse_args()

    d = ARM_ROOT / args.arm / f"round_{args.round}" / "top5"
    files = sorted(d.glob("*.top5.json"))
    if not files:
        raise SystemExit(f"no top5 files in {d}")

    ov, rank_t, rank_e, p_t, p_e, argmax_same = [], [], [], [], [], []
    for f in files:
        for t in json.load(open(f, encoding="utf-8"))["turns"]:
            for i in range(t["n_tokens"]):
                a, b = t["target"]["top"][i], t["elicited"]["top"][i]
                if not a or not b:
                    continue          # position 0 of a sequence has no predecessor
                sa, sb = {s for s, _ in a}, {s for s, _ in b}
                ov.append(len(sa & sb))
                argmax_same.append(a[0][0] == b[0][0])
                tok = t["tokens"][i]
                rank_t.append(next((j for j, (s, _) in enumerate(a) if s == tok), None))
                rank_e.append(next((j for j, (s, _) in enumerate(b) if s == tok), None))
                p_t.append(math.exp(t["target"]["lp"][i]) * 100)
                p_e.append(math.exp(t["elicited"]["lp"][i]) * 100)

    n = len(ov)
    print(f"arm {args.arm}  —  tokens generated by this run, scored under BOTH contexts")
    print(f"{len(files)} transcripts, {n} positions\n")

    print("top-5 set overlap  |target ∩ elicited|")
    for k in range(6):
        c = ov.count(k)
        print(f"  {k}: {c:5d}  {100*c/n:5.1f}%  {'#'*round(50*c/n)}")
    print(f"  mean {st.mean(ov):.3f} / 5")
    print(f"  same top-1 token: {100*sum(argmax_same)/n:.1f}%\n")

    print("where the EMITTED token sits in each context's own top-5")
    for name, r in (("target", rank_t), ("elicited", rank_e)):
        inn = sum(1 for x in r if x is not None)
        print(f"  {name:9s} rank1 {100*sum(1 for x in r if x==0)/n:5.1f}%   "
              f"in top-5 {100*inn/n:5.1f}%   outside {100*(n-inn)/n:5.1f}%")

    print("\nprobability of the emitted token (echo path, both contexts)")
    print(f"  target   mean {st.mean(p_t):6.2f}%   median {st.median(p_t):6.2f}%")
    print(f"  elicited mean {st.mean(p_e):6.2f}%   median {st.median(p_e):6.2f}%")


if __name__ == "__main__":
    main()
